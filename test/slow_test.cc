// The exact decimal path: stod and stof reach libc only for what they cannot decide themselves.
//
// Under round to nearest every decimal text converts without libc: the 64-bit table decides most, the
// big-integer comparison (strict_stox_detail::fp_slow) the rest, whatever the digits, the exponent or the
// range. libc is reached for hex floats, inf and nan, whitespace, a sign of "+", trailing text, a rounding
// mode other than nearest, a locale whose decimal point is not '.', and the two results whose errno
// differs between libcs: an exactly representable subnormal (glibc sets ERANGE only for an inexact one,
// Apple's libc for every one) and a text that rounds up from below the subnormal range into the smallest
// normal value.
//
// The test counts the calls that reach libc (-DSTRICT_STOX_COUNT_LIBC makes stod and stof call a counting
// wrapper) and checks these things:
//   1. a curated table, with expected values from exact rational arithmetic (tools/slow_cases.py), none from
//      a libc: this includes the text on which Apple's strtod aborts, which must not reach libc at all;
//   2. the texts that must reach libc, against libc;
//   3. the exact halfway point between every pair of neighbouring floats of a few hundred random pairs, and
//      the specials (subnormals, the smallest normal, the largest finite), built here as exact decimal text
//      with a big-integer routine independent of the library, with a tail of digits added or taken so that
//      the text lies just above or just below it: the result is known by construction (a tie goes to the even
//      mantissa) and the text must not reach libc unless it is one of the two cases above;
//   4. random decimal texts of every length and exponent: the exact path with and without the table
//      (fp_slow<R, false> and fp_slow<R, true>) must agree, the API must equal libc, and libc must be reached
//      only for the cases above.
//   5. the route of a text: the first byte of a text that is not decimal ('-' and then a digit or '.') sends it to strto*
//      without a try of the fast path or the exact path, and a decimal text never reaches strto*; an integer out of range
//      is decided without strto*.
// Where libc may abort on valid text (Apple), the text is first tried in a child process.
#ifndef STRICT_STOX_COUNT_LIBC
#error "build this test with -DSTRICT_STOX_COUNT_LIBC=1"
#endif


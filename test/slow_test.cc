static std::string clip(const std::string& s) { return s.size() <= 90 ? s : s.substr(0, 60) + "..." + s.substr(s.size() - 20) + " (" + std::to_string(s.size()) + " chars)"; }

template <typename R>
static bool bits_equal(R a, R b) { return std::memcmp(&a, &b, sizeof(R)) == 0; }

// True when libc can convert the text without aborting (Apple's strtod aborts on some valid text).
static bool libc_safe(const std::string& s) {
#if defined(__APPLE__)
	const pid_t p = fork();
	if (p == 0) {
		char* e;
		(void)std::strtod(s.c_str(), &e);
		(void)std::strtof(s.c_str(), &e);
		_exit(0);
	}
	int st = 0;
	waitpid(p, &st, 0);
	return WIFEXITED(st) && WEXITSTATUS(st) == 0;
#else
	(void)s;
	return true;
#endif
}

struct Api {
	oracle::Result r;
	bool libc;  // the call reached libc
};

template <typename R>
static Api api(const std::string& s, bool useidx = false) {
	const std::size_t before = D::libc_calls;
	Api a;
	a.r = oracle::api_result<R>(s, useidx);
	a.libc = D::libc_calls != before;
	return a;
}


// Checks one result against an expectation of kind N, E or L.
template <typename R>
static void check_want(const std::string& text, const Want& w, const char* what, bool negative = false) {
	const Api a = api<R>(text);
	std::uint64_t want_bits = sizeof(R) == 4 ? (w.bits & 0xffffffffULL) : w.bits;
	if (negative) { want_bits |= 1ULL << (sizeof(R) * 8 - 1); }
	switch (w.kind) {
		case 'N':
			if (a.libc) { FAIL("%s %s: reached libc", what, clip(text).c_str()); }
			if (a.r.err != 0 || a.r.bits != want_bits) { FAIL("%s %s: got bits %llx errno %d, want bits %llx", what, clip(text).c_str(), (unsigned long long)a.r.bits, a.r.err, (unsigned long long)want_bits); }
			break;
		case 'E':
			if (a.libc) { FAIL("%s %s: reached libc", what, clip(text).c_str()); }
			if (a.r.err != ERANGE || a.r.bits != 0) { FAIL("%s %s: got bits %llx errno %d, want ERANGE and 0", what, clip(text).c_str(), (unsigned long long)a.r.bits, a.r.err); }
			break;
		default:  // 'L': libc decides the errno; the value, when there is one, is the expected
			if (!a.libc) { FAIL("%s %s: did not reach libc", what, clip(text).c_str()); }
			if (!((a.r.err == 0 && a.r.bits == want_bits) || (a.r.err == ERANGE && a.r.bits == 0))) { FAIL("%s %s: got bits %llx errno %d, want bits %llx", what, clip(text).c_str(), (unsigned long long)a.r.bits, a.r.err, (unsigned long long)want_bits); }
			break;
	}
	// Whatever libc is reached or not, the answer is libc's (where libc survives the text), unless libc is wrong: FreeBSD's strtof
	// returns the smallest normal value (and no errno) for some texts of subnormal size, which the construction above has right.
	if (libc_safe(text)) {
		const oracle::Result lc = oracle::libc_result<R>(text, false);
		const std::uint64_t hidden = 1ULL << D::fp_traits<R>::mant;
		const std::uint64_t mag = lc.bits & ~(1ULL << (sizeof(R) * 8 - 1));
		if (w.kind == 'E' && lc.err == 0 && mag >= hidden) {
			++libc_bugs;
		} else if (!oracle::same(a.r, lc, false)) {
			FAIL("%s %s: differs from libc: api bits %llx errno %d, libc bits %llx errno %d (reached libc: %d); the text: %s", what, clip(text).c_str(), (unsigned long long)a.r.bits, a.r.err, (unsigned long long)lc.bits,
				lc.err, (int)a.libc, text.size() <= 400 ? text.c_str() : "(long)");
		}
	}
}

static void test_curated() {
	for (const Case& c : cases) {
		const std::string t = c.text;
		check_want<double>(t, c.d, "stod");
		check_want<float>(t, c.f, "stof");
	}
	// With idx: the whole text, and an error leaves idx alone.
	for (const Case& c : cases) {
		const std::string t = c.text;
		const Api a = api<double>(t, true);
		if (c.d.kind == 'N' && (a.r.err != 0 || a.r.idx != t.size())) { FAIL("stod idx %s: err %d idx %zu", clip(t).c_str(), a.r.err, a.r.idx); }
	}
}

// ---- 2. what must reach libc ----------------------------------------------------------------------------

static void test_reach_libc() {
	static const char* const texts[] = {"0x1p3", "0x1.8p1", "-0X1P-2", "inf", "-inf", "infinity", "nan", "NAN", "nan(0x1)", "  1", "1 ", "+1", "1e", "1e+", "1.5abc", "1,5", "1..2", ".", "-", "", "e5", "1e5x", "0x", "0x.8"};
	for (const char* c : texts) {
		const std::string t = c;
		if (!libc_safe(t)) { continue; }
		for (bool useidx : {false, true}) {
			const Api d = api<double>(t, useidx);
			const Api f = api<float>(t, useidx);
			if (!d.libc) { FAIL("stod \"%s\" (idx %d): did not reach libc", c, (int)useidx); }
			if (!f.libc) { FAIL("stof \"%s\" (idx %d): did not reach libc", c, (int)useidx); }
			if (!oracle::same(d.r, oracle::libc_result<double>(t, useidx), useidx)) { FAIL("stod \"%s\" (idx %d): differs from libc", c, (int)useidx); }
			if (!oracle::same(f.r, oracle::libc_result<float>(t, useidx), useidx)) { FAIL("stof \"%s\" (idx %d): differs from libc", c, (int)useidx); }
		}
	}
	// A directed rounding mode is libc's.
	static const int dir[] = {FE_UPWARD, FE_DOWNWARD, FE_TOWARDZERO};
	for (int mode : dir) {
		const int saved = std::fegetround();
		if (std::fesetround(mode) != 0) { continue; }
		for (const char* c : {"0.1", "9007199254740993", "1e400", "2.2250738585072011e-308", "123456789012345678901234567890"}) {
			const std::string t = c;
			const Api d = api<double>(t);
			if (!d.libc) { FAIL("stod \"%s\" in rounding mode %d: did not reach libc", c, mode); }
			if (!oracle::same(d.r, oracle::libc_result<double>(t, false), false)) { FAIL("stod \"%s\" in rounding mode %d: differs from libc", c, mode); }
		}
		std::fesetround(saved);
	}
	// And back in the default mode, nothing reaches libc for these.
	for (const char* c : {"0.1", "9007199254740993", "1e400", "2.2250738585072011e-308"}) {
		if (api<double>(c).libc) { FAIL("stod \"%s\" reached libc in the default rounding mode", c); }
	}
}

// ---- 3. exact halfway points ----------------------------------------------------------------------------

// The exact decimal text of m * 2^e2, m > 0, by schoolbook multiplication in base 10^9: nothing of the
// library is used.
static std::string exact_text(std::uint64_t m, int e2) {
	std::vector<std::uint32_t> limb;  // little endian, base 1e9
	for (std::uint64_t v = m; v != 0; v /= 1000000000ULL) { limb.push_back(static_cast<std::uint32_t>(v % 1000000000ULL)); }
	const auto mul = [&](std::uint32_t k) {
		std::uint64_t carry = 0;
		for (std::uint32_t& x : limb) {
			const std::uint64_t t = static_cast<std::uint64_t>(x) * k + carry;
			x = static_cast<std::uint32_t>(t % 1000000000ULL);
			carry = t / 1000000000ULL;
		}
		while (carry != 0) {
			limb.push_back(static_cast<std::uint32_t>(carry % 1000000000ULL));
			carry /= 1000000000ULL;
		}
	};
	int n = e2 >= 0 ? e2 : -e2;
	const std::uint32_t base = e2 >= 0 ? 2u : 5u;
	const std::uint32_t chunk = e2 >= 0 ? (1u << 29) : 1220703125u;  // 2^29, 5^13
	const int per = e2 >= 0 ? 29 : 13;
	for (; n >= per; n -= per) { mul(chunk); }
	for (; n > 0; --n) { mul(base); }
	std::string digits = std::to_string(limb.back());
	for (std::size_t i = limb.size() - 1; i-- > 0;) {
		const std::string part = std::to_string(limb[i]);
		digits.append(9 - part.size(), '0');
		digits += part;
	}
	if (e2 >= 0) { return digits; }
	const std::size_t j = static_cast<std::size_t>(-e2);
	if (digits.size() <= j) { digits.insert(0, j - digits.size() + 1, '0'); }
	digits.insert(digits.size() - j, ".");
	return digits;
}

static std::string above_text(std::string t, int zeros) {  // the value plus 10^-(zeros + the digits of t after the point + 1)
	if (t.find('.') == std::string::npos) { t += '.'; }
	t.append(static_cast<std::size_t>(zeros), '0');
	t.push_back('1');
	return t;
}

static std::string below_text(std::string t, int nines) {  // the value minus a hair
	const bool dot = t.find('.') != std::string::npos;
	for (std::size_t i = t.size(); i-- > 0;) {
		if (t[i] == '.') { continue; }
		if (t[i] > '0') {
			--t[i];
			break;
		}
		t[i] = '9';
	}
	if (!dot) { t += '.'; }
	t.append(static_cast<std::size_t>(nines), '9');
	return t;
}

// Text strictly between the neighbours b and b + 1 (bit patterns of R, b + 1 possibly infinity).
template <typename R>
static void check_between(std::uint64_t b, const std::string& text, int where /* -1 below the tie, 0 the tie, 1 above */, bool negative = false) {
	using tr = D::fp_traits<R>;
	const std::uint64_t hidden = 1ULL << tr::mant;
	const std::uint64_t inf = static_cast<std::uint64_t>(tr::max_be) << tr::mant;
	std::uint64_t f = b;
	if (where > 0 || (where == 0 && (b & 1) != 0)) { f = b + 1; }
	Want w;
	if (f >= inf || f < hidden) {
		w = {'E', 0};  // overflow, or an inexact subnormal (or zero)
	} else if (f == hidden && b == hidden - 1) {
		w = {'L', f};  // rounded up into the smallest normal value
	} else {
		w = {'N', f};
	}
	check_want<R>(text, w, sizeof(R) == 4 ? "stof(between)" : "stod(between)", negative);
	// The two exact variants agree.
	R x = 0, y = 0;
	const int sx = D::fp_slow<R, false>(x, text);
	const int sy = D::fp_slow<R, true>(y, text);
	if (sx != sy || (sx == 1 && !bits_equal(x, y))) { FAIL("fp_slow variants differ on %s: %d %d", clip(text).c_str(), sx, sy); }
	const int want_status = w.kind == 'N' ? 1 : (w.kind == 'E' ? 2 : 0);
	if (sx != want_status) { FAIL("fp_slow on %s: status %d, want %d", clip(text).c_str(), sx, want_status); }
}

template <typename R>
static void test_between(std::mt19937_64& rng, int random_count) {
	using tr = D::fp_traits<R>;
	const std::uint64_t hidden = 1ULL << tr::mant;
	const std::uint64_t inf = static_cast<std::uint64_t>(tr::max_be) << tr::mant;
	std::vector<std::uint64_t> bs = {0, 1, 2, 3, hidden / 2, hidden - 3, hidden - 2, hidden - 1, hidden, hidden + 1, inf - 3, inf - 2, inf - 1, static_cast<std::uint64_t>(tr::bias) << tr::mant, (static_cast<std::uint64_t>(tr::bias) << tr::mant) - 1, (static_cast<std::uint64_t>(tr::bias) << tr::mant) + 1};
	for (int i = 0; i < random_count; ++i) { bs.push_back(rng() % inf); }
	for (std::uint64_t b : bs) {
		const std::uint64_t be = b >> tr::mant;
		const std::uint64_t frac = b & (hidden - 1);
		const std::uint64_t m = be == 0 ? frac : (hidden | frac);
		const int e = (be == 0 ? 1 : static_cast<int>(be)) - tr::bias - tr::mant;  // b is m * 2^e
		const std::string tie = exact_text(2 * m + 1, e - 1);
		check_between<R>(b, tie, 0);
		for (int zeros : {0, 25, 800}) { check_between<R>(b, above_text(tie, zeros), 1); }
		for (int nines : {1, 25, 800}) { check_between<R>(b, below_text(tie, nines), -1); }
		// The sign changes nothing but the sign bit.
		check_between<R>(b, "-" + tie, 0, true);
		check_between<R>(b, "-" + above_text(tie, 3), 1, true);
		check_between<R>(b, "-" + below_text(tie, 3), -1, true);
	}
}

// The binade boundaries: 2^k exactly, a hair above and a hair below. The 19-digit prefix of such a text can lie
// below 2^k while the text lies at or above it, so the table's candidate is in the binade below the result.
template <typename R>
static void test_boundaries() {
	using tr = D::fp_traits<R>;
	for (int be = 1; be < tr::max_be; ++be) {
		const std::string t = exact_text(1, be - tr::bias);  // 2^(be - bias), exactly
		const std::uint64_t bb = static_cast<std::uint64_t>(be) << tr::mant;
		check_want<R>(t, {'N', bb}, "boundary");
		for (int tail : {20, 30, 300}) {
			check_want<R>(above_text(t, tail), {'N', bb}, "boundary above");
			// a hair below rounds to the boundary as well; below the smallest normal value that is libc's errno
			check_want<R>(below_text(t, tail), be == 1 ? Want{'L', bb} : Want{'N', bb}, "boundary below");
		}
	}
}

// The threshold T = 2^emin (1 - 2^-(mant + 1)) = (2^(mant + 1) - 1) 2^(qsub - 1), where a value starts to round up to the smallest normal
// value: its exact decimal expansion cut after n significant digits is below T (an inexact subnormal: ERANGE), and with its last digit
// raised above T (rounds up into the normal range: libc's). The texts are as short as 18 digits, so the table, not the division,
// has to tell them from T.
template <typename R>
static void test_threshold() {
	using tr = D::fp_traits<R>;
	const std::uint64_t hidden = 1ULL << tr::mant;
	const std::string full = exact_text((hidden << 1) - 1, tr::qsub - 1);
	const std::size_t first = full.find_first_not_of("0.");
	const std::vector<std::size_t> cuts = sizeof(R) == 8 ? std::vector<std::size_t>{18, 19, 20, 25, 40, 100, 300, 600, 700} : std::vector<std::size_t>{10, 12, 15, 20, 40, 80, 100};
	for (std::size_t n : cuts) {
		std::string below = full.substr(0, first + n);  // the point is before the first significant digit
		std::string above = below;
		for (std::size_t i = above.size(); i-- > 0;) {
			if (above[i] == '.') { continue; }
			if (above[i] == '9') {
				above[i] = '0';
			} else {
				++above[i];
				break;
			}
		}
		check_want<R>(below, {'E', 0}, "threshold below");
		check_want<R>(above, {'L', hidden}, "threshold above");
		R x = 0;
		if (D::fp_slow<R>(x, below) != 2) { FAIL("fp_slow on %s: not ERANGE", clip(below).c_str()); }
		if (D::fp_slow<R>(x, above) != 0) { FAIL("fp_slow on %s: not declined", clip(above).c_str()); }
	}
}

// Exactly representable subnormals, and the exact value of the smallest normal one: libc decides the errno.
template <typename R>
static void test_exact_subnormals(std::mt19937_64& rng) {
	using tr = D::fp_traits<R>;
	const std::uint64_t hidden = 1ULL << tr::mant;
	for (int i = 0; i < 40; ++i) {
		const std::uint64_t m = i < 8 ? static_cast<std::uint64_t>(i) + 1 : (rng() % (hidden - 1)) + 1;
		const std::string t = exact_text(m, tr::qsub);
		const Api a = api<R>(t);
		if (!a.libc) { FAIL("an exact subnormal %s did not reach libc", clip(t).c_str()); }
		if (!((a.r.err == 0 && a.r.bits == m) || (a.r.err == ERANGE && a.r.bits == 0))) { FAIL("an exact subnormal %s: bits %llx errno %d, want %llx", clip(t).c_str(), (unsigned long long)a.r.bits, a.r.err, (unsigned long long)m); }
		if (libc_safe(t) && !oracle::same(a.r, oracle::libc_result<R>(t, false), false)) { FAIL("an exact subnormal %s differs from libc", clip(t).c_str()); }
	}
	const std::string tmin = exact_text(hidden, tr::qsub);  // the smallest normal value, exactly
	const Api a = api<R>(tmin);
	if (a.libc || a.r.err != 0 || a.r.bits != hidden) { FAIL("the smallest normal value %s: libc %d errno %d bits %llx", clip(tmin).c_str(), (int)a.libc, a.r.err, (unsigned long long)a.r.bits); }
}

// ---- 4. random texts ------------------------------------------------------------------------------------

static std::string random_text(std::mt19937_64& rng, int it) {
	const auto rnd = [&](int n) { return static_cast<int>(rng() % static_cast<std::uint64_t>(n)); };
	std::string t;
	if (rnd(8) == 0) { t += '-'; }
	const int nd = it % 5 == 0 ? 1 + rnd(900) : 1 + rnd(25);
	const int pt = rnd(nd + 1);
	for (int i = 0; i < nd; ++i) {
		if (i == pt && rnd(2) != 0) { t += '.'; }
		char c = rnd(5) == 0 ? '0' : static_cast<char>('0' + rnd(10));
		if (i == 0 && c == '0' && rnd(2) != 0) { c = '1'; }
		t += c;
	}
	if (rnd(3) != 0) {
		const int e = rnd(4) == 0 ? rnd(700) - 350 : rnd(100) - 50;
		t += rnd(2) != 0 ? 'e' : 'E';
		if (e >= 0 && rnd(3) == 0) { t += '+'; }
		t += std::to_string(e);
	}
	return t;
}

template <typename R>
static void test_random(std::mt19937_64& rng, int count) {
	using tr = D::fp_traits<R>;
	const std::uint64_t hidden = 1ULL << tr::mant;
	long reached = 0;
	for (int it = 0; it < count; ++it) {
		const std::string t = random_text(rng, it);
		R x = 0, y = 0;
		const int sx = D::fp_slow<R, false>(x, t);
		const int sy = D::fp_slow<R, true>(y, t);
		if (sx != sy || (sx == 1 && !bits_equal(x, y))) { FAIL("fp_slow variants differ on %s: %d %d", clip(t).c_str(), sx, sy); }
		const Api a = api<R>(t);
		const bool safe = libc_safe(t);
		if (safe) {
			const oracle::Result lc = oracle::libc_result<R>(t, false);
			const std::uint64_t lmag = lc.bits & ~(1ULL << (sizeof(R) * 8 - 1));
			if (sx == 2 && lc.err == 0 && lmag >= hidden) {  // libc wrong (FreeBSD's strtof): the exact answer stands
				++libc_bugs;
			} else if (!oracle::same(a.r, lc, false)) {
				FAIL("%s differs from libc: %s", sizeof(R) == 4 ? "stof" : "stod", clip(t).c_str());
			}
		}
		if (a.libc) {
			++reached;
			// libc is reached only for a subnormal or smallest normal result (and then fp_slow declined)
			const std::uint64_t mag = a.r.bits & ~(1ULL << (sizeof(R) * 8 - 1));
			if (mag > hidden || sx != 0) { FAIL("%s reached libc: %s (status %d, bits %llx)", sizeof(R) == 4 ? "stof" : "stod", clip(t).c_str(), sx, (unsigned long long)a.r.bits); }
		}
	}
	std::printf("%s: %d random texts, %ld reached libc\n", sizeof(R) == 4 ? "stof" : "stod", count, reached);
}

// ---- the public API on the exact path ---------------------------------------------------------------------

static void test_api_semantics() {
	// errno and the value, idx untouched on ERANGE
	for (const char* c : {"1e400", "-1e400", "1e-400", "2.2250738585072011e-308", "1e99999999999999999999"}) {
		std::size_t idx = 77;
		int e = 0;
		const double v = strict_stod(&e, c, &idx);
		if (e != ERANGE || v != 0 || idx != 77) { FAIL("strict_stod(%s): errno %d value %g idx %zu", c, e, v, idx); }
		bool threw = false;
		try {
			(void)strict_stod(std::string_view(c));
		} catch (const std::out_of_range& ex) {
			threw = std::string(ex.what()) == std::string("stod: Out of range value: ") + c;
		}
		if (!threw) { FAIL("strict_stod(%s) did not throw the expected std::out_of_range", c); }
	}
	for (const char* c : {"1e40", "-1e40", "1e-50", "1.4e-45"}) {
		std::size_t idx = 77;
		int e = 0;
		const float v = strict_stof(&e, c, &idx);
		if (e != ERANGE || v != 0 || idx != 77) { FAIL("strict_stof(%s): errno %d value %g idx %zu", c, e, v, idx); }
		bool threw = false;
		try {
			(void)strict_stof(std::string_view(c));
		} catch (const std::out_of_range& ex) {
			threw = std::string(ex.what()) == std::string("stof: Out of range value: ") + c;
		}
		if (!threw) { FAIL("strict_stof(%s) did not throw the expected std::out_of_range", c); }
	}
	// the caller's errno survives, and a clean conversion stores errno 0
	errno = 4242;
	int e = -1;
	std::size_t idx = 0;
	const double v = strict_stod(&e, "9007199254740993", &idx);
	if (errno != 4242 || e != 0 || idx != 16 || v != 9007199254740992.0) { FAIL("strict_stod(9007199254740993): errno %d saved %d idx %zu value %.17g", errno, e, idx, v); }
	errno = 4242;
	(void)strict_stod(&e, "1e400");
	if (errno != 4242 || e != ERANGE) { FAIL("strict_stod(1e400): errno %d saved %d", errno, e); }
}

// ---- the 128 bit comparison against the big integer one --------------------------------------------------

static int big_compare(std::uint64_t d, int q, std::uint64_t t, std::ptrdiff_t g) {
	const std::string ds = std::to_string(d);
	std::uint8_t dg[24];
	for (std::size_t i = 0; i < ds.size(); ++i) { dg[i] = static_cast<std::uint8_t>(ds[i] - '0'); }
	D::Big X, Y;
	X.from_digits(dg, ds.size());
	if (q > 0) { X.mul_pow5(static_cast<unsigned>(q)); }
	Y.set(1);
	if (q < 0) { Y.mul_pow5(static_cast<unsigned>(-q)); }
	return D::cmp_scaled(X, Y, q, t, g);
}

// D * 10^q against t * 2^g: cmp_small and cmp_scaled must agree whenever cmp_small answers. The pairs are random with g
// chosen so the sides are close (the only case the exact path asks about), plus exact ties and their neighbours.
static void test_small_vs_big(std::mt19937_64& rng) {
	long compared = 0, same_side[3] = {0, 0, 0};
	for (int it = 0; it < 300000; ++it) {
		const int nd = 1 + static_cast<int>(rng() % 19);
		std::uint64_t d = 0;
		for (int i = 0; i < nd; ++i) { d = d * 10 + rng() % 10; }
		if (d == 0) { d = 1; }
		const int q = static_cast<int>(rng() % 55) - 27;
		const int tb = 24 + static_cast<int>(rng() % 31);
		const std::uint64_t t = (1ULL << (tb - 1)) | (rng() & ((1ULL << (tb - 1)) - 1)) | 1;
		std::ptrdiff_t g;
		if (it % 3 == 0) {  // an exact tie, when it fits
			const int j = static_cast<int>(rng() % 12);
			g = -j;
			// V = D 10^-j = D 2^-j 5^-j = t 2^-j with t = D 5^-j... build D = t * 5^j instead
			std::uint64_t p = 1;
			for (int i = 0; i < j; ++i) { p *= 5; }
			const std::uint64_t tt = (t >> 20) | 1;
			const std::uint64_t dd = tt * p;
			const int c = D::cmp_small(dd, -j, tt, g);
			const int cb = big_compare(dd, -j, tt, g);
			if (c != 0 || cb != 0) { FAIL("tie D=%llu q=%d t=%llu g=%td: small %d big %d", (unsigned long long)dd, -j, (unsigned long long)tt, g, c, cb); }
			for (int delta : {-1, 1}) {
				const int c2 = D::cmp_small(dd + delta, -j, tt, g);
				if (c2 != delta) { FAIL("tie neighbour D=%llu q=%d t=%llu g=%td: small %d want %d", (unsigned long long)(dd + delta), -j, (unsigned long long)tt, g, c2, delta); }
			}
			continue;
		}
		const long double lv = std::log2(static_cast<long double>(d)) + static_cast<long double>(q) * std::log2(10.0L);
		g = static_cast<std::ptrdiff_t>(std::llround(lv - std::log2(static_cast<long double>(t)))) + static_cast<int>(rng() % 3) - 1;
		const int cs = D::cmp_small(d, q, t, g);
		if (cs == 2) { continue; }
		const int cb = big_compare(d, q, t, g);
		++compared;
		++same_side[cb + 1];
		if (cs != cb) { FAIL("cmp_small(D=%llu, q=%d, t=%llu, g=%td) = %d, cmp_scaled %d", (unsigned long long)d, q, (unsigned long long)t, g, cs, cb); }
	}
	if (compared < 100000 || same_side[0] == 0 || same_side[2] == 0) { FAIL("the 128 bit comparison was exercised too little: %ld compared, below %ld, above %ld", compared, same_side[0], same_side[2]); }
	std::printf("cmp_small: %ld comparisons against cmp_scaled\n", compared);
}

// ---- 5. the route of a text -----------------------------------------------------------------------------

struct Route {
	std::size_t declined, strto, libc;
};
static Route route_now() { return Route{D::decline_calls, D::strto_calls, D::libc_calls}; }

// A text whose first significant byte cannot start a decimal goes straight to strto*: it is not tried by fast_fp and does not enter
// fp_decline. A valid decimal text is converted by fast_fp or by the exact path and never reaches strto*.
template <typename R>
static void check_route(const std::string& t, bool decimal_start) {
	for (const bool useidx : {false, true}) {
		const Route r0 = route_now();
		const oracle::Result got = oracle::api_result<R>(t, useidx);
		const Route r1 = route_now();
		if (decimal_start) {
			if (r1.strto != r0.strto || r1.libc != r0.libc) { FAIL("%s \"%s\" (idx %d): a decimal text reached strto*", sizeof(R) == 4 ? "stof" : "stod", clip(t).c_str(), (int)useidx); }
		} else {
			if (r1.declined != r0.declined) { FAIL("%s \"%s\" (idx %d): entered fp_decline", sizeof(R) == 4 ? "stof" : "stod", clip(t).c_str(), (int)useidx); }
			if (r1.strto != r0.strto + 1 || r1.libc != r0.libc + 1) { FAIL("%s \"%s\" (idx %d): did not reach strto*", sizeof(R) == 4 ? "stof" : "stod", clip(t).c_str(), (int)useidx); }
		}
		if (libc_safe(t) && !oracle::same(got, oracle::libc_result<R>(t, useidx), useidx)) { FAIL("%s \"%s\" (idx %d): differs from libc", sizeof(R) == 4 ? "stof" : "stod", clip(t).c_str(), (int)useidx); }
	}
}

template <typename R>
static void test_first_byte() {
	for (int b = 0; b < 256; ++b) {
		const char c = static_cast<char>(b);
		const bool digit = b >= '0' && b <= '9';
		const std::string tail = std::string(1, c) + "5";
		check_route<R>(tail, digit || b == '.' || b == '-');             // "-5" is decimal
		check_route<R>("-" + tail, digit || b == '.');                   // "--5" is not
	}
	// Decimal text of any shape starts the fast path, and the exact path takes what it declines, without strto*.
	for (const char* t : {"-.5", ".5", "-.5e1", "5", "-5", "1e400", "-1e400", ".5e-400", "-.5e400", "9007199254740993", "123456789012345678901234567890"}) { check_route<R>(t, true); }
	// A lone sign or point is declined by both and decided by strto*; the route is only the cost.
	for (const char* t : {"-", ".", "-.", "", "--", "-+", "-e5", ".e5"}) {
		const Route r0 = route_now();
		const oracle::Result got = oracle::api_result<R>(t, false);
		if (route_now().strto != r0.strto + 1) { FAIL("\"%s\": did not reach strto*", t); }
		if (!oracle::same(got, oracle::libc_result<R>(t, false), false)) { FAIL("\"%s\": differs from libc", t); }
	}
}

// An integer out of range of the type strto* returns is ERANGE decided by the fast path, whatever follows the digits that left the
// range: value 0, idx untouched, the caller's errno kept, strto* not called. libc agrees that the digits overflow.
template <typename F, typename G>
static void check_erange(const char* name, F nothrow, G throwing, const std::string& t, int base, bool is_signed) {
	errno = 0;
	if (is_signed) { (void)std::strtoll(t.c_str(), nullptr, base); } else { (void)std::strtoull(t.c_str(), nullptr, base); }
	if (errno != ERANGE) { FAIL("%s \"%s\" base %d: libc does not report ERANGE (test text)", name, clip(t).c_str(), base); }
	const std::size_t s0 = D::strto_calls;
	int e = -1;
	std::size_t idx = 777;
	errno = 4242;
	const auto v = nothrow(&e, t, &idx, base);
	if (e != ERANGE || v != 0 || idx != 777 || errno != 4242) { FAIL("%s \"%s\" base %d: errno %d value %lld idx %zu kept %d", name, clip(t).c_str(), base, e, (long long)v, idx, (int)(errno == 4242)); }
	if (D::strto_calls != s0) { FAIL("%s \"%s\" base %d: reached strto*", name, clip(t).c_str(), base); }
	bool threw = false;
	try {
		(void)throwing(t, base);
	} catch (const std::out_of_range& ex) {
		threw = std::string(ex.what()) == std::string(name) + ": Out of range value: " + t;
	}
	if (!threw || D::strto_calls != s0) { FAIL("%s \"%s\" base %d: threw %d, strto* calls %zu", name, clip(t).c_str(), base, (int)threw, D::strto_calls - s0); }
}

#define ERANGE_CASE(FN, SIGNED, TEXT, BASE)                                                                                   \
	check_erange(#FN, [](int* e, const std::string& s, std::size_t* i, int b) { return strict_##FN(e, s, i, b); },           \
	             [](const std::string& s, int b) { return strict_##FN(s, nullptr, b); }, TEXT, BASE, SIGNED)

static void test_int_range() {
	// Wider than 64 bits for every function: unsigned and signed, with and without trailing text.
	for (const char* t : {"18446744073709551616", "99999999999999999999", "99999999999999999999x", "99999999999999999999 5", "184467440737095516150", "000000000000000000000018446744073709551616",
	                      "99999999999999999999999999999999999999999999999999999999999999"}) {
		ERANGE_CASE(stoull, false, t, 10);
		ERANGE_CASE(stoul, false, t, 10);
		ERANGE_CASE(stoz, false, t, 10);
		ERANGE_CASE(stou, false, t, 10);
		ERANGE_CASE(stoll, true, t, 10);
		ERANGE_CASE(stol, true, t, 10);
		ERANGE_CASE(stoi, true, t, 10);
		ERANGE_CASE(stoll, true, std::string("-") + t, 10);
		ERANGE_CASE(stol, true, std::string("-") + t, 10);
		ERANGE_CASE(stoi, true, std::string("-") + t, 10);
	}
	// The edge of the signed range, in the text where only the last digit leaves it (text after the digits is left to strto*).
	for (const char* t : {"9223372036854775808", "9223372036854775809"}) { ERANGE_CASE(stoll, true, t, 10); }
	for (const char* t : {"-9223372036854775809", "-9223372036854775810"}) { ERANGE_CASE(stoll, true, t, 10); }
	// Other bases.
	for (const char* t : {"10000000000000000", "ffffffffffffffffff", "FFFFFFFFFFFFFFFFFFg", "ffffffffffffffffffffffffffffffffffffffff"}) {
		ERANGE_CASE(stoull, false, t, 16);
		ERANGE_CASE(stoll, true, t, 16);
	}
	for (const char* t : {"zzzzzzzzzzzzzzzzz", "zzzzzzzzzzzzzzzzzzzzzzzz"}) { ERANGE_CASE(stoull, false, t, 36); }
	for (const char* t : {"2000000000000000000000", "7777777777777777777777"}) { ERANGE_CASE(stoull, false, t, 8); }
	// What is in range is converted by the fast path, with no strto*: the value of the limits.
	const std::size_t s0 = D::strto_calls;
	int e = -1;
	if (strict_stoull(&e, "18446744073709551615") != 18446744073709551615ULL || e != 0) { FAIL("stoull(2^64-1): errno %d", e); }
	if (strict_stoll(&e, "9223372036854775807") != 9223372036854775807LL || e != 0) { FAIL("stoll(2^63-1): errno %d", e); }
	if (strict_stoll(&e, "-9223372036854775808") != -9223372036854775807LL - 1 || e != 0) { FAIL("stoll(-2^63): errno %d", e); }
	if (D::strto_calls != s0) { FAIL("the limits of the types reached strto*"); }
}

// An integer of at most 19 digits is below 2^64, so the exact path converts it with one correctly rounded conversion and asks the table
// nothing: the exact halfway points of the doubles from 2^53 to 2^63 (and the floats from 2^24), the integers next to them, with a sign, an
// exponent or a fraction that leaves the value an integer. Values are libc's, and no el_candidate call and no libc call is made.
template <typename R>
static void test_integer_ties(std::mt19937_64& rng) {
	constexpr int mant = D::fp_traits<R>::mant;
	std::vector<std::string> texts;
	for (int e = 1; e <= 63 - mant - 1; ++e) {
		for (int i = 0; i < 12; ++i) {
			const std::uint64_t m = (1ULL << mant) + (i == 0 ? 0 : i == 1 ? (1ULL << mant) - 1 : rng() % (1ULL << mant));
			const std::uint64_t v = (2 * m + 1) << (e - 1);  // halfway between m 2^e and (m + 1) 2^e
			for (const std::uint64_t x : {v, v - 1, v + 1}) { texts.push_back(std::to_string(x)); }
		}
	}
	for (const char* t : {"9223372036854775808", "9223372036854775809", "9999999999999999999", "18014398509481986", "16777217", "16777219", "33554434"}) { texts.push_back(t); }
	const std::size_t base = texts.size();
	for (std::size_t i = 0; i < base; ++i) {  // the same integers written with an exponent or a fraction
		const std::string& t = texts[i];
		if (t.size() < 19) { texts.push_back(t + "e0"); }
		if (t.size() < 18) { texts.push_back(t + "0e-1"); }
		if (t.size() > 3) { texts.push_back(t.substr(0, t.size() - 2) + "." + t.substr(t.size() - 2) + "e2"); }
	}
	for (const std::string& pos : texts) {
		for (const std::string& t : {pos, "-" + pos}) {
			const std::size_t c0 = D::candidate_calls;
			const Api a = api<R>(t);
			// (Text of at most 19 digits is safe for libc: Apple's strtod aborts on texts of 40 digits and more.)
			if (!oracle::same(a.r, oracle::libc_result<R>(t, false), false)) { FAIL("%s %s: differs from libc", sizeof(R) == 4 ? "stof" : "stod", clip(t).c_str()); }
			if (a.libc) { FAIL("%s %s: reached libc", sizeof(R) == 4 ? "stof" : "stod", clip(t).c_str()); }
			// A text of at most 19 digits whose value is the integer needs no table: that is the shortcut. (The fast path takes most
			// of them first, and the table the rest; the halfway points are the texts that reach the shortcut.)
			if (t.find_first_of(".e") == std::string::npos && D::candidate_calls != c0) { FAIL("%s %s: asked the table", sizeof(R) == 4 ? "stof" : "stod", clip(t).c_str()); }
		}
	}
}

// Zero texts, straight into the exact path (the fast path takes them first, so only a direct call reaches the branch): +0 or -0 by
// the sign, whatever the digits and the exponent.
template <typename R>
static void test_zero_direct() {
	for (const char* t : {"0", "-0", "0.0", "-0.000", ".0", "-.0", "-0e5", "0e5", "-0E-5", "00000", "-0000.0000e+99999999999999999999", "0e-99999999999999999999"}) {
		const std::string s = t;
		R v = 1;
		const int st = D::fp_slow<R>(v, s);
		const bool neg = s[0] == '-';
		const std::uint64_t want = neg ? 1ULL << (sizeof(R) * 8 - 1) : 0;
		if (st != 1 || oracle::to_bits(v) != want) { FAIL("fp_slow<%s>(\"%s\"): status %d bits %llx, want 1 and %llx", sizeof(R) == 4 ? "float" : "double", t, st, (unsigned long long)oracle::to_bits(v), (unsigned long long)want); }
	}
}


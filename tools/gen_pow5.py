#!/usr/bin/env python3
"""Generate (or verify) the 5^q table used by strict_stox.hh's Eisel-Lemire path.

Usage:
    tools/gen_pow5.py            print the table block
    tools/gen_pow5.py --write    splice the table into strict_stox.hh between its markers
    tools/gen_pow5.py --check    exit 1 unless strict_stox.hh already holds this table

For each decimal exponent q in [QMIN, QMAX] the table holds the 64 most significant
bits of 5^q, truncated, as an integer T in [2^63, 2^64):

    q >= 0:  T = floor(5^q / 2^(bl-64))        (bl = bit length of 5^q; shifted left if bl < 64)
    q <  0:  T = floor(2^(63+bl) / 5^-q)       (bl = bit length of 5^-q)

so that 5^q = (T + eps) * 2^(f(q) - 63) with 0 <= eps < 1, and
f(q) = floor(log2(5^q)).  The header derives the binary exponent of w * 10^q
from g(q) = f(q) + q = floor(q * log2(10)), computed as (q * 217706) >> 16;
this script proves that identity for every q in range.

QMIN = -326 is the smallest q for which a 64-bit w can still give a normal
double (w * 10^q >= 2^-1022 needs 10^q >= 2^-1022 / 2^64, q >= -326.9);
QMAX = 308 is the largest q with 10^q <= DBL_MAX.
"""
import os
import re
import sys

QMIN, QMAX = -326, 308


def f_exact(q):
    """floor(log2(5^q)) computed with big integers."""
    if q >= 0:
        return (5 ** q).bit_length() - 1
    # 5^q = 1 / 5^-q, never a power of two for q < 0 (q != 0): floor = -bit_length(5^-q)
    return -((5 ** -q).bit_length())


def entry(q):
    if q >= 0:
        p = 5 ** q
        bl = p.bit_length()
        t = p >> (bl - 64) if bl >= 64 else p << (64 - bl)
    else:
        p = 5 ** -q
        bl = p.bit_length()
        t = (1 << (63 + bl)) // p
    assert (1 << 63) <= t < (1 << 64), q
    return t


def check_exponents():
    for q in range(QMIN - 20, QMAX + 21):
        g = (q * 217706) >> 16
        assert g == f_exact(q) + q, (q, g, f_exact(q) + q)
        # and f(q) matches the exponent the table entry was normalised with
        if q >= 0:
            assert (5 ** q).bit_length() - 1 == f_exact(q)


def render():
    check_exponents()
    lines = []
    row = []
    for q in range(QMIN, QMAX + 1):
        row.append("0x%016xULL" % entry(q))
        if len(row) == 4:
            lines.append("\t" + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("\t" + ", ".join(row) + ",")
    return "\n".join(lines)


BEGIN = "// BEGIN pow5 table (generated by tools/gen_pow5.py; do not edit)"
END = "// END pow5 table"


def main():
    body = render()
    block = "%s\n%s\n%s" % (BEGIN, body, END)
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "strict_stox.hh")
    if "--check" in sys.argv or "--write" in sys.argv:
        with open(path, encoding="utf-8") as fh:
            src = fh.read()
        m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), src, re.S)
        if not m:
            sys.stderr.write("strict_stox.hh has no pow5 table markers\n")
            return 1
        if "--write" in sys.argv:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(src[:m.start()] + block + src[m.end():])
            print("pow5 table written (%d entries)" % (QMAX - QMIN + 1))
            return 0
        if m.group(0) != block:
            sys.stderr.write("strict_stox.hh pow5 table is stale\n")
            return 1
        print("pow5 table OK (%d entries)" % (QMAX - QMIN + 1))
        return 0
    print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
